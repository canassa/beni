#!/usr/bin/env bash
# Regenerates tests/browser/parse5.mjs: parse5, the HTML standard's parsing
# algorithm as the standard writes it (§13.2), bundled by rolldown into one
# ES module that imports nothing. The `browser/` driver builds the tree an
# `insertAdjacentHTML` string makes with it, so a page shows the tree the
# standard's parser makes and not happy-dom's lenient one: browser-inline
# leaves end tags out of its markup (docs/design/browser-inline.md §8.2),
# and a string a real parser reads differently fails its page's golden.
#
# No network: the packages are taken from a node_modules directory on this
# machine (the first argument; by default the reactivity-research project's
# Solid setup, where npm installed them), and their versions are checked
# against the pins below. Run it by hand to move the pin, then update
# `parse5_id` and `parse5_sha256` in tests/blackbox/browser.zig with what
# it prints, run `zig build test-run-hashes` (every browser record changes)
# and commit them together. The same packages give the same bytes.
set -euo pipefail

PARSE5=7.3.0
ENTITIES=6.0.1
ROLLDOWN=1.2.14

here="$(cd "$(dirname "$0")" && pwd)"
modules="$(cd "${1:-$here/../../../reactivity-research/frameworks/solid/node_modules}" && pwd)"
for pin in "parse5 $PARSE5" "entities $ENTITIES" "rolldown $ROLLDOWN"; do
  set -- $pin
  got="$(node -p "require('$modules/$1/package.json').version")"
  [ "$got" = "$2" ] || { echo "vendor-parse5.sh: $1 is $got in $modules, not the pinned $2" >&2; exit 1; }
done

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cd "$work"
ln -s "$modules" node_modules
echo 'export { parseFragment, defaultTreeAdapter } from "parse5";' >entry.mjs
node_modules/.bin/rolldown entry.mjs --format esm --minify --platform neutral --file bundle.mjs >/dev/null

{
  echo "// parse5 $PARSE5 (MIT, © 2013-2019 Ivan Nikulin) and entities $ENTITIES"
  echo "// (BSD-2-Clause, © Felix Böhm), bundled by rolldown $ROLLDOWN from the copies"
  echo "// npm installed in reactivity-research's frameworks/solid/node_modules;"
  echo "// licences at the end. Generated by tests/browser/vendor-parse5.sh: do not"
  echo "// edit."
  cat bundle.mjs
  echo
  echo "/*"
  for p in parse5 entities; do
    echo " * $p $(node -p "require('$modules/$p/package.json').version") ($(node -p "require('$modules/$p/package.json').license"))"
    sed 's#\*/#* /#g; s#^# *   #; s# *$##' "$modules/$p/LICENSE"
    echo " *"
  done
  echo " */"
} >"$here/parse5.mjs"

echo "parse5_id: parse5-$PARSE5"
echo "parse5_sha256: $(sha256sum "$here/parse5.mjs" | cut -d' ' -f1)"
