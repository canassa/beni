//! A platform compiled into beni from outside its source tree
//! (docs/design/boundary.md §9.5). `build.zig` builds a beni with
//! `tests/platforms/toy` compiled in, exactly as `zig build
//! -Dplatform=tests/platforms/toy` does, and runs this file against that
//! binary: `--platform=toy` finds the platform by name as it finds one that
//! ships, its `toy` markup lowering — Zig written against interface 1.0 and
//! importing `html`'s Zig module — is in the binary's registry, and a program
//! built for it prints what that lowering made of its view.
//!
//! Boundary 2: the emitted program under Node. Nothing here imports a
//! compiler internal.

const std = @import("std");
const world = @import("world.zig");
const World = world.World;
const testing = std.testing;

test "an external platform's markup lowering compiles a view the program then prints" {
    // ┌─────────────────────────────────────────┐
    // │ PREPARE                                 │
    // └─────────────────────────────────────────┘
    // The toy lowering writes an element as its tag and its content in
    // brackets through a function its `module` hoisted, a void element as
    // `br/` (from `html`'s parser table), quotes a text hole through its
    // runtime, and names every element's tag as program start data, which
    // the entry file hands the runtime's `start` — sorted and without
    // repeats — before `run`. Its runtime is the program runtime too, so
    // the one file is checked against the union with `run`.
    var w = try World.init(testing.allocator, testing.io);
    defer w.deinit();
    try w.write("Main.beni",
        \\import Html exposing (Html)
        \\import Toy
        \\
        \\
        \\view : String → Html msg
        \\view name =
        \\    <p>Hi {name}<br /><b>{Html.text "!"}</b><b>?</b></p>
        \\
        \\
        \\main : Toy.Program
        \\main =
        \\    Toy.show (view "you")
        \\
    );

    // ┌─────────────────────────────────────────┐
    // │ EXECUTE                                 │
    // └─────────────────────────────────────────┘
    const built = try w.runWith(&.{ "build", "--platform=toy", "--out=out", "Main.beni" }, .{ .raw_diagnostics = true });

    // ┌─────────────────────────────────────────┐
    // │ VERIFY OUTPUT                           │
    // └─────────────────────────────────────────┘
    try testing.expectEqual(@as(u8, 0), built.exit_code);
    try testing.expectEqualStrings("", built.stderr);
    try w.expectProgram("out/_main.mjs", .{ .stdout = "p[\"Hi \" \"you\" br/[] b[\"!\"] b[\"?\"]]\ntags: b br p\n" });

    // ┌─────────────────────────────────────────┐
    // │ VERIFY SIDE EFFECTS                     │
    // └─────────────────────────────────────────┘
    // One runtime file, copied once: it is the program runtime and the
    // markup runtime both.
    const entry = try w.read("out/_main.mjs");
    try testing.expectEqualStrings(
        \\// Generated by `beni build` (docs/design/boundary.md §5.2): the entry file
        \\// the platform's output shape asks for.
        \\import { run } from "./_platform/runtime.foreign.mjs";
        \\import { start } from "./_platform/runtime.foreign.mjs";
        \\import { Main$main } from "./Main.mjs";
        \\
        \\start({"tag": ["b", "br", "p"]});
        \\run(Main$main);
        \\
    , entry);
}

test "a release application calls the runtime's start and run inside its one file" {
    // ┌─────────────────────────────────────────┐
    // │ PREPARE                                 │
    // └─────────────────────────────────────────┘
    // The toy runtime is the program runtime and the markup runtime both.
    // Under `--release` an application is one scope-hoisted file
    // (`backend.md` §9, *One scope-hoisted file under `--release`*): the
    // runtime, the toy sibling and `Main`, in the order the entry file would
    // have evaluated them, then the entry's `start` and `run` calls by the
    // names those bindings have in the one scope. The development build keeps
    // its two `import` lines, pinned above.
    var w = try World.init(testing.allocator, testing.io);
    defer w.deinit();
    try w.write("Main.beni",
        \\import Html exposing (Html)
        \\import Toy
        \\
        \\
        \\view : String → Html msg
        \\view name =
        \\    <p>Hi {name}</p>
        \\
        \\
        \\main : Toy.Program
        \\main =
        \\    Toy.show (view "you")
        \\
    );

    // ┌─────────────────────────────────────────┐
    // │ EXECUTE                                 │
    // └─────────────────────────────────────────┘
    const built = try w.runWith(&.{ "build", "--platform=toy", "--release", "--out=out", "Main.beni" }, .{ .raw_diagnostics = true });

    // ┌─────────────────────────────────────────┐
    // │ VERIFY OUTPUT                           │
    // └─────────────────────────────────────────┘
    try testing.expectEqual(@as(u8, 0), built.exit_code);
    try testing.expectEqualStrings("", built.stderr);
    try w.expectProgram("out/_main.mjs", .{ .stdout = "p[\"Hi \" \"you\"]\ntags: p\n" });

    // ┌─────────────────────────────────────────┐
    // │ VERIFY SIDE EFFECTS                     │
    // └─────────────────────────────────────────┘
    try testing.expectEqualStrings(
        \\import process from"node:process";let e=[];const g=a=>{e=a.tag};const h=c=>{process.stdout.write(`${c.html.t}\ntags: ${e.join(" ")}\n`)};const b=d=>`"${d}"`;const a=html=>({html});function c(a){return"p["+a+"]"}const d=a({t:c("\"Hi \" "+b("you"))});g({"tag":["p"]});h(d);
        \\
    , try w.read("out/_main.mjs"));
}

test "typed lowering closes generic operand packets with checked source evidence" {
    // ┌─────────────────────────────────────────┐
    // │ PREPARE                                 │
    // └─────────────────────────────────────────┘
    var w = try World.init(testing.allocator, testing.io);
    defer w.deinit();
    try w.copyTreeInto("core", "mycore", "_");
    try w.write("mycore/CaptureCheck.beni",
        \\import Js.Data as Data
        \\pub data value =
        \\    case Data.checked value of
        \\        Just _ → "data"
        \\        Nothing → "hidden"
    );
    try w.write("platform/beni.json",
        \\{"platform":true,"name":"evidence","platforms":["html"],"reexports":["Html"],"program":"Probe.Program","runtime":"runtime.js","markup":{"lowering":"typed-toy","module":"Probe","runtime":"runtime.js"}}
    );
    try w.write("platform/runtime.js",
        \\export const run = program => console.log(program.t);
        \\export const text = value => ({t: value});
        \\export const map = (value, tagger) => value;
    );
    try w.write("platform/Probe.js", "export const show = value => value;\n");
    try w.write("platform/Probe.beni",
        \\import Html exposing (Html)
        \\import Js.Any as Any
        \\import CaptureCheck
        \\
        \\pub foreign type Program
        \\pub foreign pure show : Html msg → Program
        \\pub opaque type Saved = Saved Any.Any
        \\pub save value = Saved (Any.pack value)
        \\
        \\pub first rows = List.head rows
        \\pub sample rows =
        \\    case rows of
        \\        [ ( _, _, _, value ), …_ ] → value.sample
        \\        [] → sample rows
        \\
        \\pub keyValue : List (Saved × Saved × Saved × { sample : a, keyOf : a → key }) → key
        \\keyValue rows =
        \\    case rows of
        \\        [ ( _, _, _, value ), …_ ] → value.keyOf value.sample
        \\        [] → keyValue rows
        \\
        \\read : Any.Any, a → Maybe a
        \\read saved _ = Any.unpack saved
        \\
        \\pub inspect : List (Saved × Saved × Saved × { sample : a, keyOf : a → key }) → String
        \\inspect rows =
        \\    case rows of
        \\        [ ( Saved firstBox, Saved secondBox, _, value ), …_ ] →
        \\            original = read firstBox value.sample
        \\            originalKey = read secondBox (value.keyOf value.sample)
        \\            case ( original, originalKey ) of
        \\                ( Just _, Just _ ) → "matched"
        \\                _ → "wrong identity"
        \\        [] → "empty"
        \\
        \\pub capture : Saved, packet → String
        \\capture (Saved saved) example =
        \\    original = read saved example
        \\    case original of
        \\        Just _ → "tuple matched"
        \\        Nothing → "tuple identity changed"
        \\
        \\pub data value = CaptureCheck.data value
    );
    try w.write("src/View.beni",
        \\import Html exposing (Html)
        \\import Probe
        \\
        \\pub view : List (Probe.Saved × Probe.Saved × Probe.Saved × { sample : a, keyOf : a → key }) → Html msg
        \\view rows =
        \\    render : List (Probe.Saved × Probe.Saved × Probe.Saved × { sample : a, keyOf : a → key }) → Html msg
        \\    render input = <For each={input} keyed={False}>{λ_ → <></>}</For>
        \\    render rows
    );
    try w.write("src/Main.beni",
        \\import Probe
        \\import View
        \\
        \\main : Probe.Program
        \\main =
        \\    value = { count = 42, names = [ "one", "two" ] }
        \\    key = "key"
        \\    rows = [ ( Probe.save value, Probe.save key, Probe.save ( value, key ), { sample = value, keyOf = λ_ → key } ) ]
        \\    Probe.show (View.view rows)
    );
    // ┌─────────────────────────────────────────┐
    // │ EXECUTE                                 │
    // └─────────────────────────────────────────┘
    // Cold, warm, then release: the packet's identity is independently made
    // by a normal Beni call, while the consumer is a lowering-generated call.
    for ([_][]const []const u8{
        &.{ "build", "--platform=platform", "--core-root=mycore", "--out=out", "--roundtrip-dispatch", "--root=src", "src" },
        &.{ "build", "--platform=platform", "--core-root=mycore", "--out=out", "--root=src", "src" },
        &.{ "build", "--platform=platform", "--core-root=mycore", "--out=out", "--release", "--root=src", "src" },
    }) |args| {
        const built = try w.runWith(args, .{ .raw_diagnostics = true });
        // ┌─────────────────────────────────────┐
        // │ VERIFY OUTPUT                       │
        // └─────────────────────────────────────┘
        if (built.exit_code != 0) std.debug.print("{s}\n", .{built.stderr});
        try testing.expectEqual(@as(u8, 0), built.exit_code);
        try testing.expectEqualStrings("", built.stderr);
        try w.expectProgram("out/_main.mjs", .{ .stdout = "matched/matched/tuple matched/data\n" });
    }
}
