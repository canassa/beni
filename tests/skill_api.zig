//! `zig build skill-api` (docs/design/frontend.md §12.4): the generated part
//! of the skill for coding agents, `skills/beni/references/api-*.md` — the
//! public interface of every core module and of every platform in the
//! binary, as `beni dump --stage=interface` prints it.
//!
//!   beni-skill-api <beni> <repo-root> <out-dir> [<package>]
//!
//! One `dump` per package, over its directory, so the cost is one process
//! per file written. Each file is one header, one paragraph that says how
//! to read a type, and the dump in a `text` fence — rewritten into beni's
//! own notation (§12.1): an agent copies a signature from this file, so it
//! holds nothing a program cannot write. Every effect class (`!e1`,
//! `!(impure | e1)`, `!sync`), the words `foreign` and `markup`, the mark
//! `(equatable)` and a constructor's `/n` arity go; `Never` is written `⊥`;
//! a value whose own result is `impure` or `suspends` keeps that one fact
//! as a trailing comment. The black-box gate (`tests/blackbox/skill_test.zig`)
//! runs this tool into a temporary directory and compares byte for byte,
//! so a change to a public signature fails the gate until the step is run
//! again.

const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;

/// The packages, in the order their files are written. `core` is the core
/// package; every other name is a platform under `platforms/`.
pub const packages = [_][]const u8{ "core", "node", "browser", "browser-tea", "browser-inline", "html", "cloudflare" };

pub const header =
    \\Generated by `zig build skill-api` from `beni dump --stage=interface`. Do not edit this file:
    \\change the source it describes, then run the step.
    \\
    \\Each module lists its public types, with their constructors indented below, and its public
    \\values with their types, in beni's own notation. A function type lists its parameters before
    \\one arrow: `List a, (a → b) → List b`. A `where` clause names the methods a type variable
    \\needs. Effects are inferred and never written; a value whose result reaches the host or may
    \\wait says so in a trailing comment, `-- impure` or `-- suspends`.
    \\
;

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4 and args.len != 5) {
        std.debug.print("usage: beni-skill-api <beni> <repo-root> <out-dir> [<package>]\n", .{});
        return 2;
    }
    const beni = args[1];
    const root = args[2];
    const out = args[3];
    // One package, for a gate that holds one package per test (§12.4).
    const only: ?[]const u8 = if (args.len == 5) args[4] else null;
    try Io.Dir.cwd().createDirPath(io, out);
    var out_dir = try Io.Dir.cwd().openDir(io, out, .{});
    defer out_dir.close(io);
    for (packages) |package| {
        if (only) |o| if (!std.mem.eql(u8, o, package)) continue;
        const text = try generate(arena, io, beni, root, package);
        const name = try std.fmt.allocPrint(arena, "api-{s}.md", .{package});
        try out_dir.writeFile(io, .{ .sub_path = name, .data = text });
    }
    return 0;
}

/// The Markdown for one package.
pub fn generate(arena: Allocator, io: Io, beni: []const u8, root: []const u8, package: []const u8) ![]const u8 {
    const is_core = std.mem.eql(u8, package, "core");
    const dir = if (is_core)
        try std.fs.path.join(arena, &.{ root, "core" })
    else
        try std.fs.path.join(arena, &.{ root, "platforms", package });
    var argv: std.ArrayList([]const u8) = .empty;
    try argv.appendSlice(arena, &.{ beni, "dump", "--stage=interface", "--jobs=1" });
    try argv.append(arena, try std.fmt.allocPrint(arena, "--root={s}", .{dir}));
    if (is_core) {
        try argv.append(arena, "--core");
    } else {
        try argv.append(arena, try std.fmt.allocPrint(arena, "--platform={s}", .{package}));
    }
    try argv.append(arena, dir);
    const r = try std.process.run(arena, io, .{ .argv = argv.items });
    const code: u8 = switch (r.term) {
        .exited => |c| c,
        else => 255,
    };
    if (code != 0 or r.stderr.len != 0) {
        std.debug.print("beni-skill-api: `beni dump --stage=interface` on {s} exited {d}:\n{s}\n", .{ dir, code, r.stderr });
        return error.UnexpectedExit;
    }
    var text: std.ArrayList(u8) = .empty;
    const title = if (is_core) "core" else try std.fmt.allocPrint(arena, "the `{s}` platform", .{package});
    try text.print(arena, "# The public interface of {s}\n\n", .{title});
    try text.appendSlice(arena, header);
    try text.appendSlice(arena, "```text\n");
    var lines = std.mem.splitScalar(u8, r.stdout, '\n');
    var in_never = false;
    while (lines.next()) |line| {
        if (line.len == 0 and lines.peek() == null) break;
        // `type Never` in Basics and its constructor line: one comment (§12.1).
        if (std.mem.eql(u8, line, "  type Never")) {
            in_never = true;
            try text.appendSlice(arena, "  -- ⊥ is declared here: the type with no values\n");
            continue;
        }
        if (in_never and std.mem.startsWith(u8, line, "    ")) continue;
        in_never = false;
        try text.appendSlice(arena, try surface(arena, line));
        try text.append(arena, '\n');
    }
    try text.appendSlice(arena, "```\n");
    return text.items;
}

/// One dump line in beni's notation (§12.1).
pub fn surface(arena: Allocator, line: []const u8) ![]const u8 {
    var s = line;
    const indent = s.len - std.mem.trimStart(u8, s, " ").len;
    const body = s[indent..];
    var out: std.ArrayList(u8) = .empty;
    try out.appendNTimes(arena, ' ', indent);
    // A constructor line: `Just/1` → `Just`.
    if (indent == 4) {
        const slash = std.mem.lastIndexOfScalar(u8, body, '/');
        const arity = if (slash) |i| body[i + 1 ..] else "";
        if (slash != null and arity.len != 0 and std.mem.indexOfScalar(u8, arity, ' ') == null and allDigits(arity)) {
            try out.appendSlice(arena, try replaceNever(arena, body[0..slash.?]));
            return out.items;
        }
    }
    var rest = body;
    for ([_][]const u8{ "foreign ", "markup " }) |word| {
        if (std.mem.startsWith(u8, rest, word)) rest = rest[word.len..];
    }
    if (std.mem.endsWith(u8, rest, " (equatable)")) rest = rest[0 .. rest.len - " (equatable)".len];
    // A value's own result class is the class before its `where` clause.
    var comment: []const u8 = "";
    if (std.mem.startsWith(u8, rest, "value ")) {
        const head = if (std.mem.indexOf(u8, rest, " where ")) |i| rest[0..i] else rest;
        if (tailClass(head)) |class| {
            if (std.mem.indexOf(u8, class, "suspends") != null) {
                comment = "  -- suspends";
            } else if (std.mem.indexOf(u8, class, "impure") != null) {
                comment = "  -- impure";
            }
        }
    }
    try out.appendSlice(arena, try replaceNever(arena, try stripClasses(arena, rest)));
    try out.appendSlice(arena, comment);
    return out.items;
}

fn allDigits(s: []const u8) bool {
    for (s) |c| if (!std.ascii.isDigit(c)) return false;
    return true;
}

/// The effect class a type ends with — `impure`, `e1`, `(impure | e1)` — or null.
fn tailClass(s: []const u8) ?[]const u8 {
    const t = std.mem.trimEnd(u8, s, " ");
    if (t.len == 0) return null;
    if (t[t.len - 1] == ')') {
        const open = std.mem.lastIndexOf(u8, t, " !(") orelse return null;
        if (std.mem.indexOfScalar(u8, t[open + 3 ..], ')') != t.len - open - 4) return null;
        return t[open + 2 ..];
    }
    const bang = std.mem.lastIndexOf(u8, t, " !") orelse return null;
    const class = t[bang + 2 ..];
    if (class.len == 0) return null;
    for (class) |c| if (!std.ascii.isAlphanumeric(c)) return null;
    return class;
}

/// `s` without any ` !<class>`: a name, or a parenthesised join.
fn stripClasses(arena: Allocator, s: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < s.len) {
        if (s[i] == ' ' and i + 1 < s.len and s[i + 1] == '!') {
            var j = i + 2;
            if (j < s.len and s[j] == '(') {
                while (j < s.len and s[j] != ')') j += 1;
                if (j < s.len) j += 1;
            } else {
                while (j < s.len and std.ascii.isAlphanumeric(s[j])) j += 1;
            }
            i = j;
            continue;
        }
        try out.append(arena, s[i]);
        i += 1;
    }
    return out.items;
}

/// The word `Never` as beni writes it, `⊥`.
fn replaceNever(arena: Allocator, s: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < s.len) {
        const word = "Never";
        const at_start = i == 0 or !std.ascii.isAlphanumeric(s[i - 1]);
        const at_end = i + word.len >= s.len or !std.ascii.isAlphanumeric(s[i + word.len]);
        if (at_start and std.mem.startsWith(u8, s[i..], word) and at_end) {
            try out.appendSlice(arena, "⊥");
            i += word.len;
            continue;
        }
        try out.append(arena, s[i]);
        i += 1;
    }
    return out.items;
}

test "a dump line becomes beni's notation" {
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const cases = [_][2][]const u8{
        .{ "  value map : List a, (a → b !e1) → List b !e1", "  value map : List a, (a → b) → List b" },
        .{ "  value sleep : Duration → ⊤ !suspends", "  value sleep : Duration → ⊤  -- suspends" },
        .{ "  value get : Ref a → a !impure", "  value get : Ref a → a  -- impure" },
        .{ "  value compare : List a, List a → Order !e1 where a.compare : a, a → Order !(e1 | sync)", "  value compare : List a, List a → Order where a.compare : a, a → Order" },
        .{ "  value bracket : (⊤ → r !e1), (r, Exit a → ⊤ !e2), (r → a !e3) → a !(impure | e1 | e2 | e3)", "  value bracket : (⊤ → r), (r, Exit a → ⊤), (r → a) → a  -- impure" },
        .{ "  foreign type List a (equatable)", "  type List a" },
        .{ "  markup value text : String → Html msg", "  value text : String → Html msg" },
        .{ "    Just/1", "    Just" },
        .{ "    Nothing", "    Nothing" },
        .{ "  type NeverKind", "  type NeverKind" },
        .{ "  value expectJson : Expect Error a !(impure | e1) where a.codec : ⊤ → Codec a !e1", "  value expectJson : Expect Error a where a.codec : ⊤ → Codec a  -- impure" },
        .{ "  value value : (Generator a !e1) → a !(impure | e1)", "  value value : (Generator a) → a  -- impure" },
        .{ "  value never : ⊥ → a", "  value never : ⊥ → a" },
        .{ "module Maybe", "module Maybe" },
    };
    for (cases) |c| {
        try std.testing.expectEqualStrings(c[1], try surface(arena, c[0]));
    }
}
