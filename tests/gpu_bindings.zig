//! `zig build gpu-bindings` writes the generated WebGPU modules
//! (`docs/design/webgpu.md` §2.2) from the pinned @webref/idl archive; the
//! tests here run in `zig build test`, a gate, and fail when a committed file
//! is not the generator's output for the pin (the staleness check), when the
//! uniform-exposure assertion of §2.3 stops refusing, or when an IDL
//! declaration of `webgpu.idl` is neither generated nor excluded with a reason.
const std = @import("std");
const Native = @import("native_bindings");
const Gpu = Native.Gpu;

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: beni-gpu-bindings <pinned-idl-archive.tgz> <repository-root>\n", .{});
        return 2;
    }
    const archive = try std.Io.Dir.cwd().readFileAlloc(init.io, args[1], arena, .limited(Native.max_archive_bytes + 1));
    const files = switch (try generate(arena, archive)) {
        .success => |files| files,
        .failure => |d| {
            std.debug.print("{t}: {s} (offset {d})\n", .{ d.code, d.detail, d.offset });
            return 1;
        },
    };
    // Every file is generated before the first is written.
    var root = try std.Io.Dir.cwd().openDir(init.io, args[2], .{});
    defer root.close(init.io);
    for (files) |file| {
        if (std.fs.path.dirname(file.path)) |dir| try root.createDirPath(init.io, dir);
        try root.writeFile(init.io, .{ .sub_path = file.path, .data = file.bytes });
    }
    return 0;
}

pub fn generate(arena: std.mem.Allocator, archive: []const u8) !Gpu.Result {
    const catalogue = switch (try Native.generate(arena, archive)) {
        .success => |c| c,
        .failure => |d| return .{ .failure = .{ .code = .missing_input, .detail = d.detail } },
    };
    return Gpu.generate(arena, catalogue);
}

test "committed WebGPU modules are exactly the generator's output for the pin" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const result = try generate(a, @embedFile("webref_idl"));
    if (result == .failure) {
        std.debug.print("{any}\n", .{result.failure});
        return error.GenerationFailed;
    }
    var stale: usize = 0;
    for (result.success) |file| {
        const actual = std.Io.Dir.cwd().readFileAlloc(std.testing.io, file.path, a, .limited(4 * 1024 * 1024)) catch |err| {
            std.debug.print("{s}: {t}; run `zig build gpu-bindings`\n", .{ file.path, err });
            stale += 1;
            continue;
        };
        if (!std.mem.eql(u8, actual, file.bytes)) {
            std.debug.print("{s} is stale; run `zig build gpu-bindings`\n", .{file.path});
            stale += 1;
        }
    }
    // A generated file the generator no longer writes is stale too.
    var dir = try std.Io.Dir.cwd().openDir(std.testing.io, Gpu.core_dir, .{ .iterate = true });
    defer dir.close(std.testing.io);
    var it = dir.iterate();
    while (try it.next(std.testing.io)) |entry| {
        if (!std.mem.endsWith(u8, entry.name, ".beni")) continue;
        const bytes = try dir.readFileAlloc(std.testing.io, entry.name, a, .limited(64 * 1024));
        if (!std.mem.startsWith(u8, bytes, "-- Generated by `zig build gpu-bindings`")) continue;
        const path = try std.fmt.allocPrint(a, "{s}/{s}", .{ Gpu.core_dir, entry.name });
        for (result.success) |file| {
            if (std.mem.eql(u8, file.path, path)) break;
        } else {
            std.debug.print("{s} is generated but no longer written; run `zig build gpu-bindings` and remove it\n", .{path});
            stale += 1;
        }
    }
    try std.testing.expectEqual(@as(usize, 0), stale);
}

test "the generator's output is deterministic" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const one = (try generate(arena.allocator(), @embedFile("webref_idl"))).success;
    const two = (try generate(arena.allocator(), @embedFile("webref_idl"))).success;
    try std.testing.expectEqual(one.len, two.len);
    for (one, two) |x, y| {
        try std.testing.expectEqualStrings(x.path, y.path);
        try std.testing.expectEqualStrings(x.bytes, y.bytes);
    }
}

fn countIn(haystack: []const u8, needle: []const u8) usize {
    return std.mem.count(u8, haystack, needle);
}

fn find(files: []const Gpu.Output, path: []const u8) []const u8 {
    for (files) |f| if (std.mem.eql(u8, f.path, path)) return f.bytes;
    return "";
}

test "every declaration of webgpu.idl is generated or excluded with a reason" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const c = (try Native.generate(a, @embedFile("webref_idl"))).success;
    const files = (try Gpu.generate(a, c)).success;
    const types = find(files, Gpu.platform_dir ++ "/Types.beni");
    const flags = find(files, Gpu.platform_dir ++ "/Flags.beni");
    const native = find(files, Gpu.platform_dir ++ "/Native.beni");
    var counts: struct { interfaces: usize = 0, dictionaries: usize = 0, enums: usize = 0, values: usize = 0, constants: usize = 0, unions: usize = 0 } = .{};
    for (c.declarations) |d| {
        if (!std.mem.eql(u8, c.files[d.file].path, Gpu.idl_file) or d.partial) continue;
        switch (d.kind) {
            .interface => {
                counts.interfaces += 1;
                const path = try std.fmt.allocPrint(a, "{s}/{s}.beni", .{ Gpu.core_dir, d.name });
                try std.testing.expect(find(files, path).len != 0);
            },
            .dictionary => {
                counts.dictionaries += 1;
                var excluded = false;
                for (Gpu.excluded_dictionaries) |e| excluded = excluded or std.mem.eql(u8, e.idl, d.name);
                if (excluded) continue;
                const decl = try std.fmt.allocPrint(a, "--| `{s}`.\npub type alias {s} =", .{ d.name, Gpu.typeName(d.name) });
                try std.testing.expect(std.mem.find(u8, types, decl) != null);
                const to_native = try std.fmt.allocPrint(a, "--| The native `{s}`.\n", .{d.name});
                try std.testing.expect(std.mem.find(u8, native, to_native) != null);
                // Every member of the dictionary is a field of its record
                // and set by its conversion under its IDL name.
                for (c.members[d.members_start..d.members_end]) |member| {
                    const text = member.source_span.text(c.files[member.file].source);
                    // The member's name is the last word before its default or `;`.
                    const end = std.mem.findScalar(u8, text, '=') orelse std.mem.findScalar(u8, text, ';').?;
                    const head = std.mem.trimEnd(u8, text[0..end], " \t\r\n");
                    const name = head[(std.mem.findLastAny(u8, head, " \t\r\n") orelse return error.MemberWithoutName) + 1 ..];
                    try std.testing.expect(name.len != 0);
                    const set = try std.fmt.allocPrint(a, "out \"{s}\"", .{name});
                    try std.testing.expect(std.mem.find(u8, native, set) != null);
                }
            },
            .enumeration => {
                counts.enums += 1;
                const decl = try std.fmt.allocPrint(a, "--| `{s}`.\npub type {s}\n", .{ d.name, Gpu.typeName(d.name) });
                try std.testing.expect(std.mem.find(u8, types, decl) != null);
                const text = d.source_span.text(c.files[d.file].source);
                var at: usize = 0;
                while (std.mem.findScalarPos(u8, text, at, '"')) |open| {
                    const close = std.mem.findScalarPos(u8, text, open + 1, '"').?;
                    counts.values += 1;
                    // The spelling is written in both conversions.
                    try std.testing.expect(countIn(types, text[open .. close + 1]) >= 2);
                    at = close + 1;
                }
            },
            .namespace => for (c.members[d.members_start..d.members_end]) |member| {
                counts.constants += 1;
                const text = member.source_span.text(c.files[member.file].source);
                var words = std.mem.tokenizeAny(u8, text, " \t;=");
                _ = words.next();
                _ = words.next();
                const name = words.next().?;
                const value = try std.fmt.parseInt(u32, words.next().?, 0);
                const line = try std.fmt.allocPrint(a, "\n            {d}\n", .{value});
                try std.testing.expect(std.mem.find(u8, flags, line) != null);
                _ = name;
            },
            .typedef => {
                const text = d.source_span.text(c.files[d.file].source);
                var words = std.mem.tokenizeAny(u8, text, " \t\r\n");
                const is_union = while (words.next()) |word| {
                    if (std.mem.eql(u8, word, "or")) break true;
                } else false;
                if (!is_union) continue;
                counts.unions += 1;
                var mapped = false;
                for (Gpu.unions) |u| mapped = mapped or std.mem.eql(u8, u.key, d.name);
                try std.testing.expect(mapped);
            },
            else => {},
        }
    }
    // The pin's census (docs/design/research/webgpu/coverage.md).
    try std.testing.expectEqual(@as(usize, 36), counts.interfaces);
    try std.testing.expectEqual(@as(usize, 62), counts.dictionaries);
    try std.testing.expectEqual(@as(usize, 34), counts.enums);
    try std.testing.expectEqual(@as(usize, 26), counts.constants);
    try std.testing.expectEqual(@as(usize, 6), counts.unions);
}

fn indexOne(a: std.mem.Allocator, source: []const u8) !Native.Catalogue {
    return indexTwo(a, source, "");
}

fn indexTwo(a: std.mem.Allocator, source: []const u8, html: []const u8) !Native.Catalogue {
    const files = [_]Native.File{ .{ .path = "html.idl", .source = html }, .{ .path = Gpu.idl_file, .source = source } };
    return (try Native.index(a, try a.dupe(Native.File, &files))).success;
}

test "the generator refuses a WebGPU declaration exposed other than (Window, Worker)" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const cases = [_]struct { source: []const u8, detail: []const u8 }{
        .{ .source = "[Exposed=Window, SecureContext] interface GPUThing {};", .detail = "GPUThing" },
        .{ .source = "[Exposed=(Window, Worker, ServiceWorker)] interface GPUThing {};", .detail = "GPUThing" },
        .{ .source = "[Exposed=(Window, Worker)] interface GPUThing { [Exposed=Window] undefined only(); };", .detail = "[Exposed=Window] undefined only();" },
        .{ .source = "[Exposed=(Window, Worker)] namespace GPUThings {};" ++ "[Exposed=DedicatedWorker] partial namespace GPUThings {};", .detail = "GPUThings" },
    };
    for (cases) |case| {
        const result = try Gpu.generate(a, try indexOne(a, case.source));
        try std.testing.expectEqual(Gpu.Code.exposure_mismatch, result.failure.code);
        try std.testing.expectEqualStrings(case.detail, result.failure.detail);
    }
    // A mixin of webgpu.idl that a Window-only interface alone includes.
    const mixin = try Gpu.generate(a, try indexTwo(a, "interface mixin GPUMix {}; Host includes GPUMix;", "[Exposed=Window] interface Host {};"));
    try std.testing.expectEqual(Gpu.Code.exposure_mismatch, mixin.failure.code);
    try std.testing.expectEqualStrings("GPUMix", mixin.failure.detail);
    // The pin itself passes the assertion; a Window-only interface outside
    // webgpu.idl that includes a mixin of it, beside a Worker one, is fine.
    const ok = try Gpu.generate(a, try indexTwo(a, "interface mixin NavGPU {}; Nav includes NavGPU; WorkerNav includes NavGPU;", "[Exposed=Window] interface Nav {}; [Exposed=Worker] interface WorkerNav {};"));
    try std.testing.expect(ok == .failure);
    try std.testing.expect(ok.failure.code != .exposure_mismatch);
}

test "no public signature of the public Gpu modules names Js, and browser-tea hides the engine" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    // `Gpu.Engine` and `Gpu.Native` are the engine's own: their signatures
    // name `Js.Value`, and `browser-tea` re-exports neither.
    const internal = [_][]const u8{ "Engine.beni", "Native.beni" };
    var files: std.ArrayList([]const u8) = .empty;
    try files.append(a, "platforms/browser/Gpu.beni");
    var dir = try std.Io.Dir.cwd().openDir(std.testing.io, Gpu.platform_dir, .{ .iterate = true });
    defer dir.close(std.testing.io);
    var it = dir.iterate();
    while (try it.next(std.testing.io)) |entry| {
        if (!std.mem.endsWith(u8, entry.name, ".beni")) continue;
        var skip = false;
        for (internal) |name| skip = skip or std.mem.eql(u8, name, entry.name);
        if (!skip) try files.append(a, try std.fmt.allocPrint(a, "{s}/{s}", .{ Gpu.platform_dir, entry.name }));
    }
    try std.testing.expect(files.items.len >= 10);
    for (files.items) |path| {
        const bytes = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, path, a, .limited(4 * 1024 * 1024));
        var lines = std.mem.splitScalar(u8, bytes, '\n');
        while (lines.next()) |line| {
            if (!std.mem.startsWith(u8, line, "pub ")) continue;
            if (std.mem.find(u8, line, "Js.") != null) {
                std.debug.print("{s}: a public signature names Js: {s}\n", .{ path, line });
                return error.JsInPublicSignature;
            }
        }
    }
    const tea = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "platforms/browser-tea/beni.json", a, .limited(64 * 1024));
    try std.testing.expect(std.mem.find(u8, tea, "\"Gpu.Engine\"") == null);
    try std.testing.expect(std.mem.find(u8, tea, "\"Gpu.Native\"") == null);
    try std.testing.expect(std.mem.find(u8, tea, "\"Gpu.Types\"") != null);
}
