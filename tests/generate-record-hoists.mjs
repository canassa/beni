#!/usr/bin/env node
// Value-semantics answers are recorded by test-blackbox-corpus while the
// compiler still spreads records. The same sources become differential
// tests when record stores and the stale-read sanitiser land (§31.12).
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

let seed = 315;
const next = () => {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) % 100;
};
const helpers = readFileSync(new URL("corpus/ownership/RecordHoistChannel.beni", import.meta.url), "utf8").trimEnd();
const calls = [];
for (let i = 0; i < 3; i++) {
  const x = next(), n = next();
  for (const call of [
    `old { x = ${x} } ${n}`,
    `joined { x = ${x} } True`,
    `joined { x = ${x} } False`,
    `called { x = ${x} }`,
    `aliased { x = ${x} }`,
    `captured { x = ${x} }`,
    `twice { x = ${x} }`,
    `nextArgument { x = ${x} }`,
    `capturedBefore { x = ${x} }`,
    `deep { a = { b = { c = { d = { e = { f = { g = { h = { i = { j = ${x} } } } } } } } } } }`,
  ]) calls.push(`String.fromInt (${call})`);
}
const source = `-- Generated by tests/generate-record-hoists.mjs, seed 315.\nimport Node exposing (Program)\n\n\n${helpers}\n\n\nplus : { x : Int }, Int → Int\nplus q n = q.x + n\n\n\nnextArgument : { x : Int } → Int\nnextArgument p = plus { p | x = 9 } p.x\n\n\ncapturedBefore : { x : Int } → Int\ncapturedBefore p =\n    get = λ⊤ → p.x\n    q = { p | x = 10 }\n    q.x + get ⊤\n\n\nmain : Program\nmain =\n    Node.printLines\n        [ ${calls.join("\n        , ")}\n        ]\n`;
const output = fileURLToPath(new URL("corpus/run/RecordHoistValues.beni", import.meta.url));
writeFileSync(output, source);
const formatted = spawnSync(process.env.BENI_EXE ?? "zig-out/safe/bin/beni", ["fmt", output], {
  stdio: "inherit",
});
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) throw new Error(`beni fmt failed: ${formatted.signal ?? formatted.status}`);
