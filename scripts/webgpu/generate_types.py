#!/usr/bin/env python3
"""Generate beni declarations from the audited pinned WebGPU IDL subset.

This is a repository maintenance command, never an application loader. The
runtime is ordinary committed beni. Unknown syntax/types stop generation.
"""
import argparse
import importlib.util
from pathlib import Path
import re
import sys
import subprocess

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("inventory", ROOT / "docs/design/research/webgpu/inventory.py")
inventory = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inventory)
DECLS = inventory.parse((ROOT / "docs/design/research/webgpu/webgpu.idl").read_text())
DICTS = {n: (p.removeprefix(": "), fields) for k, n, p, fields in DECLS if k == "dictionary"}
ENUMS = {n: values for k, n, p, values in DECLS if k == "enum"}
HANDLES = {"GPU" + n: "Handle." + n for n in ["Adapter", "Device", "Queue", "Buffer", "Texture", "TextureView", "Sampler", "ExternalTexture", "BindGroupLayout", "PipelineLayout", "BindGroup", "ComputePipeline", "RenderPipeline", "CommandEncoder", "CommandBuffer", "RenderBundleEncoder", "RenderBundle", "QuerySet"]}
HANDLES.update({"GPUShaderModule": "Handle.Shader", "GPUComputePassEncoder": "Handle.ComputePass", "GPURenderPassEncoder": "Handle.RenderPass", "GPUCanvasContext": "Handle.Surface"})
SCALARS = {"GPUSize64": "Scalar.Size64", "GPUIntegerCoordinate": "Scalar.U32", "GPUIndex32": "Scalar.U32", "GPUSize32": "Scalar.U32", "GPUBufferDynamicOffset": "Scalar.U32", "GPUStencilValue": "Scalar.U32", "GPUSampleMask": "Scalar.U32", "GPUDepthBias": "Scalar.I32", "GPUSignedOffset32": "Scalar.I32", "double": "Scalar.FiniteF64", "float": "Scalar.FiniteF32", "GPUPipelineConstantValue": "Scalar.FiniteF64", "USVString": "String", "DOMString": "String", "boolean": "Bool", "[Clamp] unsigned short": "Float", "PredefinedColorSpace": "ColorSpace", "GPUError": "GpuError"}
FLAGS = {"GPUBufferUsageFlags": "Flags.BufferUsages", "GPUTextureUsageFlags": "Flags.TextureUsages", "GPUShaderStageFlags": "Flags.ShaderStages", "GPUMapModeFlags": "Flags.MapModes", "GPUColorWriteFlags": "Flags.ColorWrites"}
UNIONS = {"(HTMLVideoElement or VideoFrame)": "ExternalTextureSource", "(GPUPipelineLayout or GPUAutoLayoutMode)": "PipelineLayoutMode", "(GPUTexture or GPUTextureView)": "TextureOrView", "GPUBindingResource": "BindingResource", "GPUCopyExternalImageSource": "Source.Input", "GPUColor": "Color", "GPUOrigin2D": "Origin2D", "GPUOrigin3D": "Origin3D", "GPUExtent3D": "Extent3D"}


def name(native):
    return native.removeprefix("GPU")


def ctor(enum, value):
    return name(enum) + "".join(part[0].upper() + part[1:] for part in value.split("-"))


def field_name(native):
    return {"type": "kind", "module": "shader"}.get(native, native)


def translated(native):
    if native.endswith("?"):
        return "Maybe (" + translated(native[:-1]) + ")"
    if native.startswith("sequence<") and native.endswith(">"):
        return "List (" + translated(native[9:-1]) + ")"
    if native == "record<DOMString, (GPUSize64 or undefined)>":
        return "List (String × Option Scalar.Size64)"
    if native == "record<USVString, GPUPipelineConstantValue>":
        return "List (String × Scalar.FiniteF64)"
    for table in [HANDLES, SCALARS, FLAGS, UNIONS]:
        if native in table:
            return table[native]
    if native in DICTS or native in ENUMS:
        return name(native)
    raise ValueError("Unreviewed IDL type: " + native)


def fields_of(native):
    if native == "EventInit":
        return [(False, "boolean", n) for n in ["bubbles", "cancelable", "composed"]]
    parent, fields = DICTS[native]
    result = fields_of(parent) if parent else []
    for field in fields:
        match = re.fullmatch(r"(?P<required>required )?(?P<type>.+) (?P<name>\w+)(?: = .+)?;", field.split(" = ", 1)[0].rstrip(";") + ";")
        if not match:
            raise ValueError("Unreviewed dictionary member: " + field)
        result.append((bool(match["required"]), match["type"], match["name"]))
    return result


def generate():
    out = ["--! Complete pinned WebGPU descriptor/enumeration declarations.", "--! Generated by scripts/webgpu/generate_types.py; edit the audited translator and regenerate.", "--! Default omits a property; Value explicitly supplies it. Nullable members", "--! independently use Maybe. Native fields `type`/`module` are `kind`/`shader`.", "import Gpu.Handle as Handle", "import Gpu.Scalar as Scalar", "import Gpu.Flags as Flags", "import Browser.Source as Source", "", "pub type Option a = Default | Value a", "", "pub type ColorSpace = Srgb | DisplayP3", "", "pub type GpuError = ValidationError String | OutOfMemoryError String | InternalError String", "", "pub type ExternalTextureSource = ExternalVideo Source.VideoElement | ExternalFrame Source.VideoFrame", "", "pub type PipelineLayoutMode = ExplicitLayout Handle.PipelineLayout | AutomaticLayout AutoLayoutMode", "", "pub type TextureOrView = WholeTexture Handle.Texture | TextureView Handle.TextureView", "", "pub type BindingResource = BindingSampler Handle.Sampler | BindingTexture Handle.Texture | BindingView Handle.TextureView | BindingBuffer Handle.Buffer | BindingRange BufferBinding | BindingExternal Handle.ExternalTexture", "", "pub type Color = ColorRecord ColorDict | ColorSequence (List Scalar.FiniteF64)", "", "pub type Origin2D = Origin2DRecord Origin2DDict | Origin2DSequence (List Scalar.U32)", "", "pub type Origin3D = Origin3DRecord Origin3DDict | Origin3DSequence (List Scalar.U32)", "", "pub type Extent3D = Extent3DRecord Extent3DDict | Extent3DSequence (List Scalar.U32)", ""]
    for native in ["GPUAdapterInfo", "GPUSupportedLimits"]:
        attributes = next(fields for k, n, p, fields in DECLS if k == "interface" and n == native)
        out += ["pub type alias " + name(native) + " ="]
        for attribute in attributes:
            match = re.fullmatch(r"readonly attribute (.+) (\w+);", attribute)
            assert match, attribute
            typ = {"DOMString": "String", "unsigned long": "Int", "unsigned long long": "Int", "boolean": "Bool"}[match[1]]
            out += ["    " + match[2] + " : " + typ]
        out += [""]
    for native, values in ENUMS.items():
        out += ["pub type " + name(native), "    = " + "\n    | ".join(ctor(native, v) for v in values), ""]
    for native in DICTS:
        fields = fields_of(native)
        out += ["pub type alias " + name(native) + " ="]
        if not fields:
            out += ["    ⊤", ""]
        else:
            out += ["    " + field_name(f) + " : " + (translated(t) if req else "Option (" + translated(t) + ")") for req, t, f in fields]
            out += [""]
        required = [(translated(t), field_name(f)) for req, t, f in fields if req]
        helper = name(native)[0].lower() + name(native)[1:]
        out += ["pub " + helper + " : " + (", ".join(t for t, f in required) if required else "⊤") + " → " + name(native), helper + " " + (" ".join(f for t, f in required) if required else "⊤") + " ="]
        if not fields:
            out += ["    ⊤", ""]
        else:
            out += ["    { " + "\n    , ".join(field_name(f) + " = " + (field_name(f) if req else "Default") for req, t, f in fields) + "\n    }", ""]
    return "\n\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--beni", type=Path, default=ROOT / "zig-out/bin/beni")
    parser.add_argument("--out", type=Path, default=ROOT / "platforms/browser/Gpu/Types.beni")
    args = parser.parse_args()
    scratch = ROOT / "zig-out/webgpu-generator"
    scratch.mkdir(parents=True, exist_ok=True)
    raw = scratch / "Types.beni"
    raw.write_text(generate())
    content = subprocess.run([str(args.beni), "fmt", "--stdout", str(raw)], check=True, capture_output=True, text=True).stdout
    raw.unlink()
    scratch.rmdir()
    if args.check:
        if args.out.read_text() != content:
            raise SystemExit("Generated GPU types differ: regenerate and format with beni fmt")
    else:
        args.out.write_text(content)


if __name__ == "__main__":
    main()
