// TodoMVC's shape (browser-direct.md §13, kill criterion 5): N todos, a
// keyed list of `List.filter` of them, every other one done. `#go` toggles
// the middle todo's `done` with the filter at All (the row's class changes;
// the filtered list is a new list of the same items but one); `#filter`
// switches the filter between All and Active (half the rows leave, then come
// back). There is no P3 page for this shape: research 60 wrote none.

import { beniHeader, scriptRoot, solidHeader, solidMount } from "./common.mjs";

export const target = (n) => Math.floor(n / 2);
// Whether todo `i` (0-based) starts done.
const startsDone = (i) => i % 2 === 1;
export const active = (n) => Math.ceil(n / 2);

// The middle row's class after the k-th `#go`.
export const classAfter = (k, n) => (startsDone(target(n)) !== (k % 2 === 1) ? "done" : "");

export const beni = (n) => `${beniHeader(`filtered list, ${n} todos`)}type Filter
    = All
    | Active


type Msg
    = Toggle Int
    | Cycle


type alias Todo =
    id : Int
    title : String
    done : Bool


type alias Model =
    todos : List Todo
    filter : Filter


visible : Filter, Todo → Bool
visible filter todo =
    case filter of
        All →
            True

        Active →
            not todo.done


update : Msg, Model → Model
update msg model =
    case msg of
        Toggle id →
            { model
                | todos =
                    List.map model.todos λt → if t.id == id then { t | done = not t.done } else t
            }

        Cycle →
            case model.filter of
                All →
                    { model | filter = Active }

                Active →
                    { model | filter = All }


view : Model → Html Msg
view model =
    <div class="container">
        <button type="button" id="go" onClick={Toggle ${target(n) + 1}}>go</button>
        <button type="button" id="filter" onClick={Cycle}>filter</button>
        <ul>
            <For each={List.filter model.todos (visible model.filter _)} keyed={.id}>
                {λt →
                    <li class={if t.done then "done" else ""}>
                        <input />
                        <span>{t.title}</span>
                        <button onClick={Toggle t.id}>toggle</button>
                    </li>
                }
            </For>
        </ul>
    </div>


main : Browser.Program
main =
    Tea.sandbox
        { init =
            { todos = List.initialize ${n} λi → { id = i + 1, title = "todo \${i + 1}", done = Int.mod i 2 == 1 }
            , filter = All
            }
        , update = update
        , view = view
        }
`;

// Solid's TodoMVC idiom: a store-free signal per todo's `done`, the list in a
// signal, the filter in a signal, `For` over the filtered list.
export const solid = (v, n) => `${solidHeader(v, `filtered list, ${n} todos`, ["createSignal", "createMemo", "For"])}
const App = () => {
  const todos = Array.from({ length: ${n} }, (_, i) => {
    const [done, setDone] = createSignal(i % 2 === 1);
    return { id: i + 1, title: \`todo \${i + 1}\`, done, setDone };
  });
  const [filter, setFilter] = createSignal("all");
  const shown = createMemo(() => (filter() === "all" ? todos : todos.filter((t) => !t.done())));
  const toggle = (t) => t.setDone(!t.done());
  return (
    <div class="container">
      <button type="button" id="go" onClick={() => toggle(todos[${target(n)}])}>go</button>
      <button type="button" id="filter" onClick={() => setFilter(filter() === "all" ? "active" : "all")}>filter</button>
      <ul>
        <For each={shown()}>
          {(t) => (
            <li class={t.done() ? "done" : ""}>
              <input />
              <span textContent={t.title} />
              <button onClick={() => toggle(t)}>toggle</button>
            </li>
          )}
        </For>
      </ul>
    </div>
  );
};

${solidMount("<App />")}`;

const shell = `<button type="button" id="go">go</button><button type="button" id="filter">filter</button><ul></ul>`;
const rowHtml = "<li><input><span> </span><button>toggle</button></li>";

// Vanilla: an array of todos and an array of their <li>, written directly;
// the filter takes the done rows out and puts them back in order.
export const vanilla = (n) => `// Generated by bench/ui/scaling.mjs: filtered list, ${n} todos, vanilla.
${scriptRoot}root.innerHTML = ${JSON.stringify(shell)};
const ul = root.querySelector("ul");
const tpl = document.createElement("template");
tpl.innerHTML = ${JSON.stringify(rowHtml)};
const proto = tpl.content.firstChild;
const data = [];
const lis = [];
let active = false;
const toggle = (i) => {
  const t = data[i];
  t.done = !t.done;
  lis[i].className = t.done ? "done" : "";
  if (active && t.done) lis[i].remove();
  else if (active) {
    let j = i + 1;
    while (j < data.length && data[j].done) j++;
    ul.insertBefore(lis[i], j < data.length ? lis[j] : null);
  }
};
for (let i = 0; i < ${n}; i++) {
  const li = proto.cloneNode(true);
  const done = i % 2 === 1;
  li.className = done ? "done" : "";
  li.firstChild.nextSibling.firstChild.data = \`todo \${i + 1}\`;
  li.lastChild.addEventListener("click", () => toggle(i));
  data.push({ id: i + 1, title: \`todo \${i + 1}\`, done });
  lis.push(li);
  ul.appendChild(li);
}
document.getElementById("go").addEventListener("click", () => toggle(${target(n)}));
document.getElementById("filter").addEventListener("click", () => {
  active = !active;
  if (active) {
    for (let i = 0; i < data.length; i++) if (data[i].done) lis[i].remove();
  } else {
    let next = null;
    for (let i = data.length - 1; i >= 0; i--) {
      if (data[i].done) ul.insertBefore(lis[i], next);
      next = lis[i];
    }
  }
});
`;

// No hand-written P2 page for this shape: the vanilla page stands in, so the
// sweep builds; measure it with the subjects that have a page of their own.
export const p2 = vanilla;
