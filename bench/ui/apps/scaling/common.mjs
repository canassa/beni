// Solid 1 and Solid 2 differ in where `render` and `createStore` come from:
// Solid 2 moved the DOM half to @solidjs/web and the store into solid-js.
export const solidHeader = (v, what, imports, store = []) => {
  const core = v === 1 ? imports : [...imports, ...store];
  const lines = [`// Generated by bench/ui/scaling.mjs: ${what}, Solid ${v}.`];
  if (core.length > 0) lines.push(`import { ${core.join(", ")} } from "solid-js";`);
  if (v === 1 && store.length > 0) lines.push(`import { ${store.join(", ")} } from "solid-js/store";`);
  lines.push(`import { render } from "${v === 1 ? "solid-js/web" : "@solidjs/web"}";`);
  return `${lines.join("\n")}\n`;
};

