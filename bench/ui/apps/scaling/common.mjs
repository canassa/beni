// Shared pieces of the scaling sweeps' generated programs (scaling.mjs).
// Every sweep writes, for one value of its parameter, one program per
// framework: `Main.beni` (built twice, development and `--release`),
// `solid1.jsx`, `solid2.jsx`, `p2.js` and `vanilla.js`. Each is the program
// a developer would write for that framework; nothing in one is shaped to
// win or lose a measurement.

import { readFileSync } from "node:fs";

export const range = (n) => Array.from({ length: n }, (_, i) => i);
export const chunks = (xs, size) => range(Math.ceil(xs.length / size)).map((i) => xs.slice(i * size, (i + 1) * size));
export const indent = (text, n) =>
  text
    .split("\n")
    .map((l) => (l === "" ? l : " ".repeat(n) + l))
    .join("\n");

