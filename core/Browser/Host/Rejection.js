export const create = (message) => { return new globalThis.Error(message); };
export const assign = (reason, fields) => { Object.assign(reason, fields); return null; };
export const display = (reason) => { return globalThis.String(reason); };
export const setAbandoned = (error, reports) => { error.abandonedWorkers = reports; return null; };
export const host_typeErrorMessage = (error) => { return error instanceof globalThis.TypeError ? error.message : undefined; };
export const isTypeError = (reason) => { return reason instanceof globalThis.TypeError; };
export const isError = (reason) => { return reason instanceof globalThis.Error; };
export const name = (reason) => { return reason instanceof globalThis.Error ? reason.name : ""; };
export const host_code = (reason) => { return reason instanceof globalThis.Error && typeof reason.code === "string" ? reason.code : undefined; };
export const raise = (reason) => { throw reason; };
